"""Small native XGBoost adapter with saved Stage 3 preparation, never target encoding."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

import numpy as np
import pandas as pd  # type: ignore[import-untyped]
import xgboost as xgb

from .candidate_preparation import fit_representation, transform_representation, validate_training
from .contract import ModelTrainingError


@dataclass
class FittedCandidate:
    """Native model and safe preparation state fitted on one training partition.

    Args:
        model: Native booster, stored as JSON rather than pickle.
        preparer: Existing Stage 3 JSON inference state.
    """

    model: xgb.Booster
    preparer: dict[str, Any]

    def predict(self, X: pd.DataFrame) -> pd.Series:
        """Apply saved preparation and return aligned finite binary probabilities.

        Args:
            X: Raw predictors in the fitted order; no keys or controls.

        Returns:
            Probabilities with the original row index.
        """
        matrix = transform_representation(X, self.preparer).to_numpy(dtype=np.float32)
        values = self.model.predict(xgb.DMatrix(matrix, nthread=1))
        if not np.isfinite(values).all() or not ((values >= 0) & (values <= 1)).all():
            raise ModelTrainingError("Invalid XGBoost probabilities")
        return pd.Series(values.astype(float), index=X.index)

    def model_bytes(self) -> bytes:
        """Return the native portable JSON model, excluding unsafe object snapshots."""
        return bytes(self.model.save_raw(raw_format="json"))


def restore_candidate(model_bytes: bytes, preparer: dict[str, Any]) -> FittedCandidate:
    """Restore only locally trusted, hash-verified native bytes and JSON preparation.

    Args:
        model_bytes: Verified native JSON bytes generated by this pipeline.
        preparer: Corresponding verified Stage 3 preparation state.

    Returns:
        Inference object without fitting any parameters.
    """
    model = xgb.Booster(params={"nthread": 1})
    model.load_model(bytearray(model_bytes))
    return FittedCandidate(model, preparer)


def fit_candidate(
    X: pd.DataFrame,
    y: pd.Series,
    parameters: dict[str, Any],
    *,
    seed: int,
    threads: int,
    excluded: list[str] | None = None,
) -> FittedCandidate:
    """Fit a binary CPU histogram booster and one-hot preparer on training only.

    Args:
        X: Raw training predictors; all vocabulary learning stays in these rows.
        y: Aligned binary training labels, with both classes required.
        parameters: Predeclared bounded tree/learning/regularization configuration.
        seed: Fixed model seed.
        threads: Explicit CPU thread budget.
        excluded: Declared ablation columns removed before estimation.

    Returns:
        Fitted booster and preparation state for validation/inference.
    """
    validate_training(X, y)
    preparer = fit_representation(X, excluded)
    matrix = transform_representation(X, preparer).to_numpy(dtype=np.float32)
    rounds = parameters["n_estimators"]
    params = {k: v for k, v in parameters.items() if k != "n_estimators"}
    params.update(
        objective="binary:logistic",
        tree_method="hist",
        device="cpu",
        seed=seed,
        nthread=threads,
        disable_default_eval_metric=1,
        scale_pos_weight=1,
        subsample=1,
        colsample_bytree=1,
    )
    model = xgb.train(
        params,
        xgb.DMatrix(matrix, label=y.to_numpy(dtype=int), nthread=threads),
        num_boost_round=rounds,
    )
    return FittedCandidate(model, preparer)

"""Export the resolved pip environment derived from pyproject.toml."""

from __future__ import annotations

import hashlib
import subprocess
import sys
from pathlib import Path


def main() -> None:
    """Run in the clean environment after installing all declared extras."""
    root = Path(__file__).resolve().parents[1]
    frozen = subprocess.check_output(
        [sys.executable, "-m", "pip", "freeze", "--exclude", "sat-dengue-v2"], text=True
    )
    lines = [line for line in frozen.splitlines() if line and not line.startswith("#")]
    if any("==" not in line or " @ " in line for line in lines):
        raise ValueError("Only resolved public version pins may be exported")
    source = hashlib.sha256((root / "pyproject.toml").read_bytes()).hexdigest()
    destination = root / "docs/operations/kedro-foundation-constraints.txt"
    destination.write_text(
        "# Generated by scripts/export_kedro_constraints.py; do not edit.\n"
        f"# Authority: pyproject.toml SHA-256 {source}\n"
        "# Observed Python 3.12.11 / macOS arm64; validate resolution on other platforms.\n"
        + "\n".join(sorted(lines, key=str.casefold))
        + "\n"
    )


if __name__ == "__main__":
    main()

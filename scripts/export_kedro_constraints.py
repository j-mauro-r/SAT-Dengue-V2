"""Export a full resolved environment or preserve a baseline for isolated new direct pins."""

from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import subprocess
import sys
import tomllib
from pathlib import Path

from packaging.requirements import Requirement


def preserved_lines(raw: bytes, baseline: str) -> list[str]:
    """Preserve baseline pins and verify isolated direct additions against their dependencies."""
    lines = [line for line in baseline.splitlines() if line and not line.startswith("#")]
    pins = {Requirement(line).name.lower().replace("_", "-"): Requirement(line) for line in lines}
    project = tomllib.loads(raw.decode())["project"]
    declared = project["dependencies"] + [
        v for extra in project["optional-dependencies"].values() for v in extra
    ]
    for text in declared:
        requirement = Requirement(text)
        key = requirement.name.lower().replace("_", "-")
        if key in pins:
            if pins[key].specifier != requirement.specifier:
                raise ValueError("Changed existing pin requires a clean full resolution")
            continue
        installed = importlib.metadata.version(requirement.name)
        if not requirement.specifier.contains(installed):
            raise ValueError("New declared pin not installed")
        for text in importlib.metadata.requires(requirement.name) or []:
            dependency = Requirement(text)
            if dependency.marker and not dependency.marker.evaluate({"extra": ""}):
                continue
            dep_key = dependency.name.lower().replace("_", "-")
            if dep_key not in pins or not dependency.specifier.contains(
                str(pins[dep_key].specifier).removeprefix("==")
            ):
                raise ValueError("New transitive dependency requires a clean full resolution")
        lines.append(f"{requirement.name}=={installed}")
        pins[key] = Requirement(lines[-1])
    return lines


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--preserve-baseline",
        action="store_true",
        help="Keep existing pins; verify isolated direct additions against installed metadata.",
    )
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    raw = (root / "pyproject.toml").read_bytes()
    destination = root / "docs/operations/kedro-foundation-constraints.txt"
    if args.preserve_baseline:
        old = destination.read_text()
        lines = preserved_lines(raw, old)
        origin = "# Preserves prior resolved pins; only new direct pins verified locally.\n"
        origin += "# Baseline SHA-256 " + hashlib.sha256(old.encode()).hexdigest() + "\n"
    else:
        frozen = subprocess.check_output(
            [sys.executable, "-m", "pip", "freeze", "--exclude", "sat-dengue-v2"], text=True
        )
        lines = [line for line in frozen.splitlines() if line and not line.startswith("#")]
        origin = (
            "# Observed Python 3.12.11 / macOS arm64; validate resolution on other platforms.\n"
        )
    if any("==" not in line or " @ " in line for line in lines):
        raise ValueError("Only public version pins may be exported")
    destination.write_text(
        "# Generated by scripts/export_kedro_constraints.py; do not edit.\n"
        + "# Authority: pyproject.toml SHA-256 "
        + hashlib.sha256(raw).hexdigest()
        + "\n"
        + origin
        + "\n".join(sorted(lines, key=str.casefold))
        + "\n"
    )


if __name__ == "__main__":
    main()
